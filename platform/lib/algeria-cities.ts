/**
 * Récupère la liste des communes correspondant à un identifiant de Wilaya (1 à 58).
 * Si aucune commune n'est trouvée, renvoie un tableau vide.
 */
export function getCommunesByWilayaId(wilayaId: number | string | undefined | null): string[] {
  if (!wilayaId) return [];
  const id = Number(wilayaId);
  if (isNaN(id) || !ALGERIA_COMMUNES[id]) return [];
  return ALGERIA_COMMUNES[id];
}

